def label(code):
    ch = chr(code)
    if ch == "\\":
        ch = "\\\\"
    if ch == "'":
        ch = "\\'"
    return "'%s'" % ch


def check():
    assert len(GLYPHS) == 95, "expected 95 glyphs, got %d" % len(GLYPHS)
    for i, (code, rows) in enumerate(GLYPHS):
        assert code == 0x20 + i, "glyph order broken at index %d" % i
        assert len(rows) == 8, "glyph 0x%02X has %d rows" % (code, len(rows))
        for b in rows:
            assert 0 <= b <= 0xFF
    # glyphs reaching into column 7 will visually touch the next cell
    # at 8px advance (the old 6px advance would have clipped them hard)
    wide = []
    for code, rows in GLYPHS:
        if any(b & 0x01 for b in rows):
            wide.append(chr(code))
    return wide


def preview():
    for band in range(0x20, 0x7F, 8):
        chunk = GLYPHS[band - 0x20 : band - 0x20 + 8]
        print(" ".join("%c        " % c for c, _ in chunk))
        for row in range(8):
            line = []
            for _, rows in chunk:
                line.append("".join("#" if rows[row] & (0x80 >> col) else "."
                                    for col in range(8)))
            print(" ".join(line))
        print()


HEADER = """\
#ifndef MATRIX_FONT_8X8_H
#define MATRIX_FONT_8X8_H

typedef unsigned char u8;

/* 8x8 bitmap font: the classic IBM VGA ROM character generator (CP437
 * subset, ASCII 0x20..0x7E).  MSB = leftmost pixel, row 0 = top, so the
 * renderers can use (bits & (0x80 >> col)) directly.  Baseline is row 6;
 * row 7 carries descenders (g j p q y , ;).  Glyphs are up to 8 px wide,
 * consumers advance 8 px per cell.
 *
 * GENERATED FILE - do not edit by hand.
 * Regenerate with:  python3 tools/gen_vgafont.py
 */

static const u8 matrix_font[95][8] = {
"""

FOOTER = """\
};

#endif
"""


def generate():
    out = os.path.normpath(os.path.join(os.path.dirname(__file__),
                                        "..", "include", "gfx", "88front.h"))
    lines = [HEADER]
    for code, rows in GLYPHS:
        body = ",".join("0x%02X" % b for b in rows)
        lines.append("    { %s }, /* 0x%02X %s */\n" % (body, code, label(code)))
    lines.append(FOOTER)
    with open(out, "w", newline="\n") as f:
        f.writelines(lines)
    print("wrote %s (%d glyphs)" % (out, len(GLYPHS)))


def main():
    wide = check()
    if "--preview" in sys.argv:
        preview()
        return 0
    generate()
    if wide:
        print("note: glyphs touching column 7 (fine at 8px advance): %s"
              % " ".join(wide))
    return 0


if __name__ == "__main__":
    sys.exit(main())
